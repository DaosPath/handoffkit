#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const evidencePath = join(root, "reports", "BROWSER_1.20_EVIDENCE.json");
const outPath = join(root, "reports", "BROWSER_1.20_SCORECARD.md");
const evidence = JSON.parse(readFileSync(evidencePath, "utf8"));

const titles = {
  search: "Search",
  explore: "Exploration",
  extraction: "Extraction / Markdown",
  grounding: "Grounding",
  stability: "Stability",
  browser_real: "Browser Real",
  security: "Security",
  interop: "Interoperability",
  ux: "UX",
  performance: "Performance / packaging",
};

function passCount(dimension) {
  return dimension.gates.filter((gate) => gate.result === "pass").length;
}

function renderDimension(key, dimension) {
  const score = passCount(dimension);
  const rows = dimension.gates.map((gate) => {
    const extra = gate.evidence ? ` (${gate.evidence})` : "";
    return `| ${gate.id} | ${gate.name} | ${gate.result}${extra} |`;
  }).join("\n");
  return `## ${titles[key]} (current: ${score}/10)

| # | Gate | Result |
|---|---|---|
${rows}`;
}

const scored = Object.entries(evidence.dimensions).map(([key, value]) => [key, passCount(value)]);
const atNine = scored.filter(([, score]) => score >= 9).map(([key]) => titles[key]);
const belowNine = scored.filter(([, score]) => score < 9).map(([key, score]) => `${titles[key]} ${score}/10`);
const allAtNine = atNine.length === scored.length;
const blocked = allAtNine
  ? "1.20.0 is unblocked only after a live evidence refresh."
  : "**blocked** — dimensions below 9/10 remain. Enums, mocks, and isolated helpers are not evidence.";
const dimensionSummary = atNine.length
  ? `Dimensions currently ≥9/10: ${atNine.join(", ")}. Remaining below 9: ${belowNine.join("; ") || "none"}.`
  : "No dimension has reached 9/10 with the evidence in this manifest.";
const notes = Array.isArray(evidence.notes) && evidence.notes.length
  ? `\nGrounding/release notes:\n${evidence.notes.map((note) => `- ${note}`).join("\n")}\n`
  : "";

const body = Object.entries(evidence.dimensions).map(([key, value]) => renderDimension(key, value)).join("\n\n");

const markdown = `# HandoffKit 1.20 scorecard — target 9/10 per dimension

Generated from \`reports/BROWSER_1.20_EVIDENCE.json\`. Do not edit this file by hand.
A dimension scores 9 only with nine real binary gates and no hidden fallback,
falsified telemetry, or critical/high vulnerability. There is **no average**.
The displayed score is the count of \`pass\` gates. 1.20 stays beta until every row is ≥9.

${dimensionSummary}
${notes}

Legend: \`pass\` = evidenced in this tree; \`fail\` = not yet evidenced.

${body}

## Release train

| Cut | Status |
|---|---|
| alpha.1 Core + Lite | in tree, still beta |
| alpha.2 Real + security | service rewritten; Chromium process recovery and JS mTLS dispatch green locally; hosted soak/CodeQL not live-proven |
| alpha.3 search / index / grounding | default provider order updated; live fetched-evidence oracle green; model-answer accuracy is not measured |
| beta.1 clients / Studio / Hermes | TLS clients + Studio adapter in tree; JS mTLS sockets green locally |
| rc.1 matrix / soak / packaging | local five-runtime TCP matrix, real benchmark, and clean tarball consumer green; hosted 4h/1000 soak and architecture artifacts remain |
| 1.20.0 | ${blocked} |

No PR, merge, tag, or publish from this scorecard.
`;

writeFileSync(outPath, markdown);
console.log(`wrote ${outPath}`);
